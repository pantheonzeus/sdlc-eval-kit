"""Turn stored trial logs into error_analysis.csv and RESULTS.md.

A run writes runs/<run_id>/trials.jsonl, one JSON object per trial. Everything here is
derived from those files and the human labels, so RESULTS.md can always be regenerated
byte for byte and is never edited by hand.
"""

import csv
import json
from collections import Counter, defaultdict
from pathlib import Path

from sdlc_eval_kit.stats import pass_at_1, pass_hat_k, wilson
from sdlc_eval_kit.taxonomy import LABELS, auto_hint

TRIAL_FIELDS = (
    "run_id",
    "task_id",
    "archetype",
    "model",
    "model_version",
    "trial",
    "date",
    "passed",
    "visible_passed",
    "hidden_passed",
    "touched_tests",
    "exit_status",
    "cost_eur",
    "tool_calls",
    "wall_s",
)
ERROR_COLUMNS = ("run_id", "task_id", "model", "trial", "archetype", "exit_status", "auto_hint", "label", "note")
HEADER = "<!-- Generated by `sdlc-eval results` from runs/ and results/error_analysis.csv. Do not edit by hand. -->"


def load_trials(runs_dir: Path) -> list[dict]:
    """Read every runs/*/trials.jsonl, sorted by (run, task, model, trial)."""
    trials = []
    for path in sorted(runs_dir.glob("*/trials.jsonl")):
        for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
            if not line.strip():
                continue
            record = json.loads(line)
            missing = [field for field in TRIAL_FIELDS if field not in record]
            if missing:
                raise ValueError(f"{path}:{number}: missing {', '.join(missing)}")
            trials.append(record)
    return sorted(trials, key=_key)


def export_errors(trials: list[dict], csv_path: Path) -> int:
    """Write one row per failed trial, keeping labels already given. Returns the unlabelled count."""
    existing = _read_label_rows(csv_path)
    rows = []
    for record in trials:
        if record["passed"]:
            continue
        old = existing.get(_key(record), {})
        rows.append(
            {
                "run_id": record["run_id"],
                "task_id": record["task_id"],
                "model": record["model"],
                "trial": record["trial"],
                "archetype": record["archetype"],
                "exit_status": record["exit_status"],
                "auto_hint": auto_hint(record),
                "label": old.get("label", ""),
                "note": old.get("note", ""),
            }
        )
    csv_path.parent.mkdir(parents=True, exist_ok=True)
    with csv_path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=ERROR_COLUMNS, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    return sum(1 for row in rows if not row["label"])


def load_labels(csv_path: Path) -> dict[tuple, str]:
    """Human labels by trial key. Unknown labels are an error, not a silent new category."""
    labels = {}
    for key, row in _read_label_rows(csv_path).items():
        label = row.get("label", "").strip()
        if label and label not in LABELS:
            raise ValueError(f"{csv_path}: unknown label {label!r} for {key}; allowed: {', '.join(LABELS)}")
        labels[key] = label
    return labels


def render_results(trials: list[dict], labels: dict[tuple, str]) -> str:
    """Render RESULTS.md from trials and labels."""
    if not trials:
        return f"{HEADER}\n\n# Results\n\nNo runs yet.\n"
    by_model: dict[tuple[str, str], list[dict]] = defaultdict(list)
    for record in trials:
        by_model[(record["model"], record["model_version"])].append(record)

    out = [HEADER, "", "# Results", ""]
    dates = sorted(record["date"] for record in trials)
    out.append(f"Runs from {dates[0]} to {dates[-1]}; {len(trials)} trials. 95% Wilson intervals in brackets.")
    out.append("")
    out.append("| Model | Version | Tasks | Trials | pass@1 | pass^k | €/success | € total | Tool calls | Wall s |")
    out.append("|---|---|---:|---:|---|---|---:|---:|---:|---:|")
    for (model, version), records in sorted(by_model.items()):
        out.append(_model_row(model, version, records))
    out.append("")
    out.append("pass^k uses k = the number of trials per task. Tool calls and wall time are means per trial.")
    out.append("")

    out += ["## pass@1 by archetype", "", "| Model | " + " | ".join(_archetypes(trials)) + " |"]
    out.append("|---|" + "---:|" * len(_archetypes(trials)))
    for (model, version), records in sorted(by_model.items()):
        cells = []
        for archetype in _archetypes(trials):
            subset = [r for r in records if r["archetype"] == archetype]
            cells.append(_pct(sum(r["passed"] for r in subset) / len(subset)) if subset else "—")
        out.append(f"| {model} {version} | " + " | ".join(cells) + " |")
    out.append("")

    failures = [record for record in trials if not record["passed"]]
    counts = Counter(labels.get(_key(record)) or "unlabelled" for record in failures)
    out += ["## Error analysis", "", f"{len(failures)} failed trials, {counts.get('unlabelled', 0)} unlabelled."]
    if failures:
        out += ["", "| Label | Failures | Share |", "|---|---:|---:|"]
        for label, count in sorted(counts.items(), key=lambda item: (-item[1], item[0])):
            out.append(f"| {label} | {count} | {_pct(count / len(failures))} |")
    out.append("")
    return "\n".join(out)


def _model_row(model: str, version: str, records: list[dict]) -> str:
    outcomes: dict[str, list[bool]] = defaultdict(list)
    for record in sorted(records, key=_key):
        outcomes[record["task_id"]].append(bool(record["passed"]))
    k = min(len(trials) for trials in outcomes.values())
    successes = sum(sum(trials) for trials in outcomes.values())
    n = sum(len(trials) for trials in outcomes.values())
    p1 = f"{_pct(pass_at_1(outcomes))} {_ci(successes, n)}"
    pk = _pct(pass_hat_k(outcomes, k))
    if all(len(trials) == k for trials in outcomes.values()):
        pk += " " + _ci(sum(all(trials) for trials in outcomes.values()), len(outcomes))
    cost = sum(record["cost_eur"] for record in records)
    per_success = f"{cost / successes:.2f}" if successes else "—"
    tools = sum(record["tool_calls"] for record in records) / len(records)
    wall = sum(record["wall_s"] for record in records) / len(records)
    return (
        f"| {model} | {version} | {len(outcomes)} | {n} | {p1} | pass^{k} {pk} | {per_success} | {cost:.2f} "
        f"| {tools:.1f} | {wall:.0f} |"
    )


def _archetypes(trials: list[dict]) -> list[str]:
    return sorted({record["archetype"] for record in trials})


def _ci(successes: int, n: int) -> str:
    low, high = wilson(successes, n)
    return f"[{_pct(low)}–{_pct(high)}]"


def _pct(value: float) -> str:
    return f"{value * 100:.1f}%"


def _key(record: dict) -> tuple:
    return (str(record["run_id"]), str(record["task_id"]), str(record["model"]), int(record["trial"]))


def _read_label_rows(csv_path: Path) -> dict[tuple, dict]:
    if not csv_path.is_file():
        return {}
    with csv_path.open(newline="", encoding="utf-8") as handle:
        return {_key(row): row for row in csv.DictReader(handle)}
